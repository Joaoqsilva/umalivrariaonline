/**
 * Exibe os cards de uma única página e renderiza os botões de navegação.
 */
function renderizarPagina(livros, pagina) {
    const totalPaginas = Math.ceil(livros.length / LIVROS_POR_PAGINA);
    paginaAtual = Math.min(Math.max(1, pagina), totalPaginas); 

    const startIndex = (paginaAtual - 1) * LIVROS_POR_PAGINA;
    const endIndex = startIndex + LIVROS_POR_PAGINA;
    const livrosDaPagina = livros.slice(startIndex, endIndex);

    const container = document.getElementById('container-livros');
    if (container) {
        container.innerHTML = '';

        if (livros.length === 0) {
            container.innerHTML = '<h2 style="width:100%; text-align:center; color:#555; margin-top:50px;">Nenhum livro foi encontrado. Tente outra busca ou categoria.</h2>';
        } else {
            if (livrosDaPagina.length === 0 && livros.length > 0) {
                 paginaAtual = 1;
                 return renderizarPagina(livros, 1);
            }
            livrosDaPagina.forEach(livro => adicionarLivroCard(livro));
        }
    }
    
    criarBotoesPaginacao(totalPaginas);
    focarLivroComHash(true);
}

/**
 * Cria e insere os botões de navegação da página.
 */
function criarBotoesPaginacao(totalPaginas) {
    let paginacaoDiv = document.getElementById('paginacao-livros');
    
    if (!paginacaoDiv) {
        console.warn("Elemento #paginacao-livros não encontrado. A paginação não será exibida.");
        paginacaoDiv = document.createElement('div');
        paginacaoDiv.id = 'paginacao-livros';
    }
    
    paginacaoDiv.innerHTML = '';
    
    if (totalPaginas <= 1) {
        return; 
    }

    const btnAnterior = document.createElement('button');
    btnAnterior.textContent = '<';
    btnAnterior.disabled = paginaAtual === 1;
    btnAnterior.onclick = () => irParaPagina(paginaAtual - 1);
    paginacaoDiv.appendChild(btnAnterior);

    let startPage = Math.max(1, paginaAtual - 2);
    let endPage = Math.min(totalPaginas, paginaAtual + 2);

    if (endPage - startPage < 4) {
        if (startPage === 1) endPage = Math.min(totalPaginas, 5);
        if (endPage === totalPaginas) startPage = Math.max(1, totalPaginas - 4);
    }
    
    if (startPage > 1) {
        paginacaoDiv.appendChild(criarBotaoPagina(1, 1 === paginaAtual));
        if (startPage > 2) paginacaoDiv.appendChild(Object.assign(document.createElement('span'), { textContent: '...' }));
    }

    for (let i = startPage; i <= endPage; i++) {
        const btn = criarBotaoPagina(i, i === paginaAtual);
        paginacaoDiv.appendChild(btn);
    }
    
    if (endPage < totalPaginas) {
        if (endPage < totalPaginas - 1) paginacaoDiv.appendChild(Object.assign(document.createElement('span'), { textContent: '...' }));
        paginacaoDiv.appendChild(criarBotaoPagina(totalPaginas, totalPaginas === paginaAtual));
    }


    const btnProximo = document.createElement('button');
    btnProximo.textContent = '>';
    btnProximo.disabled = paginaAtual === totalPaginas;
    btnProximo.onclick = () => irParaPagina(paginaAtual + 1);
    paginacaoDiv.appendChild(btnProximo);
}

/**
 * Função utilitária para criar um botão de página individual.
 */
function criarBotaoPagina(numPagina, isAtual) {
    const btn = document.createElement('button');
    btn.textContent = numPagina;
    btn.classList.add('btn-pagina');
    if (isAtual) {
        btn.classList.add('ativa');
        btn.disabled = true;
    }
    btn.onclick = () => irParaPagina(numPagina);
    return btn;
}

/**
 * Altera a página atual e renderiza o conteúdo.
 */
function irParaPagina(numPagina) {
    paginaAtual = numPagina;
    renderizarPagina(livrosAtuais, paginaAtual);
    window.scrollTo({ top: 0, behavior: 'smooth' });
    
    const newUrl = new URL(window.location.href);
    newUrl.searchParams.set('page', paginaAtual);
    newUrl.hash = '';
    window.history.pushState({ path: newUrl.href }, '', newUrl.href);
}

/**
 * Função que substitui a `exibirLivros` original.
 */
function exibirLivros(livrosParaExibir) {
    livrosAtuais = livrosParaExibir;
    paginaAtual = 1;
    renderizarPagina(livrosAtuais, paginaAtual);
    
    const newUrl = new URL(window.location.origin + window.location.pathname); 
    window.history.pushState({ path: newUrl.href }, '', newUrl.href);
}

