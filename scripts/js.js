/**
 * Cria e exibe um elemento de notificação toast.
 * @param {string} mensagem O texto a ser exibido no toast.
 * @param {boolean} [isContagem=false] Indica se é um toast de contagem.
 * @returns {HTMLElement} O elemento toast criado.
 */
function criarToast(mensagem, isContagem = false) {
    let toastContainer = document.getElementById('toast-container');
    if (!toastContainer) {
        toastContainer = document.createElement('div');
        toastContainer.id = 'toast-container';
        // Estilos básicos para o container (pode ser substituído por CSS)
        toastContainer.style.position = 'fixed';
        toastContainer.style.bottom = '20px';
        toastContainer.style.right = '20px';
        toastContainer.style.zIndex = '1000';
        toastContainer.style.maxWidth = '300px';
        toastContainer.style.pointerEvents = 'none'; // Permite clicar "através"
        document.body.appendChild(toastContainer);
    }

    const toast = document.createElement('div');
    toast.classList.add('custom-toast');
    toast.textContent = mensagem;

    // Estilos básicos para o toast (pode ser substituído por CSS)
    toast.style.backgroundColor = isContagem ? '#007bff' : '#28a745';
    toast.style.color = 'white';
    toast.style.padding = '10px 15px';
    toast.style.borderRadius = '5px';
    toast.style.marginBottom = '10px';
    toast.style.opacity = '0';
    toast.style.transition = 'opacity 0.3s, transform 0.3s';
    toast.style.transform = 'translateY(100%)';
    toast.style.boxShadow = '0 4px 8px rgba(0,0,0,0.2)';
    
    toastContainer.appendChild(toast);

    // Animar entrada
    setTimeout(() => {
        toast.style.opacity = '1';
        toast.style.transform = 'translateY(0)';
    }, 10);

    return toast;
}

/**
 * Mostra uma contagem decrescente no toast antes de exibir a mensagem final.
 * @param {string} titulo O título do livro para a mensagem final.
 * @param {Function} callbackDownload A função que realiza o download.
 */
function mostrarToastComContagem(titulo, callbackDownload) {
    let contagem = 5;
    const mensagemInicial = `Concluindo download de "${titulo}" em... `;
    
    const toast = criarToast(mensagemInicial + contagem, true);
      callbackDownload(); 
    const intervalo = setInterval(() => {
        contagem--;
        if (contagem >= 1) {
            toast.textContent = mensagemInicial + contagem;
        } else if (contagem === 0) {
            clearInterval(intervalo);
            
            // Realiza o download
            

            // Atualiza para a mensagem final de sucesso
            toast.style.backgroundColor = '#28a745'; 
            toast.textContent = `✅ "${titulo}" baixado! Verifique seus arquivos`;

            // Agenda a remoção do toast
            setTimeout(() => {
                toast.style.opacity = '0';
                toast.style.transform = 'translateY(100%)';
                toast.addEventListener('transitionend', () => toast.remove());
            }, 3000); // 3 segundos para a mensagem "Baixado"
            
        }
    }, 1000); // 1 segundo de intervalo

    // Limpeza em caso de navegação
    window.addEventListener('beforeunload', () => clearInterval(intervalo), { once: true });
}


