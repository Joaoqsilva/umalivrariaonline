/**
 * Aplica a classe de destaque CSS e agenda sua remoção.
 */
function aplicarDestaqueCSS(element) {
    if (elementoDestacado && elementoDestacado !== element) {
        elementoDestacado.classList.remove('destaque');
    }
    if (timeoutDestaque) {
        clearTimeout(timeoutDestaque);
    }
    
    element.classList.add('destaque');
    elementoDestacado = element;
    
    timeoutDestaque = setTimeout(() => {
        element.classList.remove('destaque');
        elementoDestacado = null;
        timeoutDestaque = null;
    }, 5000);
}


function focarLivroComHash(jaRenderizado = false) {
    const hash = window.location.hash;
    
    if (!hash) {
        if (elementoDestacado) {
            elementoDestacado.classList.remove('destaque');
            elementoDestacado = null;
            clearTimeout(timeoutDestaque);
        }
        return;
    }
    
    const targetIdDecoded = decodeURIComponent(hash.substring(1));
    const targetId = normalizarStringParaId(targetIdDecoded);
    
    let targetElement = document.getElementById(targetId);

    const urlParams = new URLSearchParams(window.location.search);
    const pageInUrl = parseInt(urlParams.get('page')) || 1;

    if (!targetElement && !jaRenderizado && pageInUrl !== paginaAtual) {
        irParaPagina(pageInUrl); 
        return;
    }
    
    if (targetElement) {
        targetElement.scrollIntoView({ behavior: 'smooth', block: 'center' });
        aplicarDestaqueCSS(targetElement);
        
    } 
    else if (!jaRenderizado) {
        const container = document.getElementById('container-livros');
        if (container) {
            const observer = new MutationObserver(() => {
                targetElement = document.getElementById(targetId);
                if (targetElement) {
                    observer.disconnect();
                    targetElement.scrollIntoView({ behavior: 'smooth', block: 'center' });
                    aplicarDestaqueCSS(targetElement);
                }
            });
            observer.observe(container, { childList: true });
        }
    }
}




