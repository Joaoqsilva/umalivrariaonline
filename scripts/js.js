/**
 * Normaliza uma string, removendo acentos, convertendo para minúsculas
 * e limpando caracteres especiais, exceto traços e underscores.
 */
function normalizarStringParaId(str) {
    if (!str) return '';
    
    const semAcentos = str.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    const limpa = semAcentos.replace(/[^\w\s-]/g, '');
    return limpa.toLowerCase().trim().replace(/[\s_-]+/g, '-');
}


const filtrarLivrosPorTituloECategoria = (termo, lista) => {
    if (!termo) {
        return lista;
    }
    const termoNormalizado = termo.toLowerCase().trim();
    return lista.filter(livro => {
        if (!livro || !livro.titulo) return false; 
        
        const tituloMatch = livro.titulo.toLowerCase().includes(termoNormalizado);
        const categoriaMatch = livro.categorias.some(categoria => 
            categoria.toLowerCase().includes(termoNormalizado)
        );
        return tituloMatch || categoriaMatch;
    });
};

/**
 * Calcula a página do livro na lista COMPLETA/ORIGINAL.
 */
function encontrarPaginaOriginalDoLivro(titulo) {
    if (typeof listaDeLivros === 'undefined' || listaDeLivros.length === 0) return 1;

    const index = listaDeLivros.findIndex(livro => livro && livro.titulo === titulo);

    if (index === -1) {
        return 1;
    }
    
    return Math.ceil((index + 1) / LIVROS_POR_PAGINA);
}


/**
 * Funções de Utilidade para Compartilhamento
 *******************************************
 */
function criarUrlDeCompartilhamento(titulo) {
    if (!titulo) return window.location.href;
    
    const idParaFoco = normalizarStringParaId(titulo);
    const paginaCorreta = encontrarPaginaOriginalDoLivro(titulo);

    const url = new URL(window.location.origin + window.location.pathname); 

    url.searchParams.set('page', paginaCorreta);
    url.hash = `#${idParaFoco}`;

    return url.toString();
}

